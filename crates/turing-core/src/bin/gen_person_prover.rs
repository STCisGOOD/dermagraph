
use std::fs;
use std::path::PathBuf;

use turing_core::{
    Fr, MerkleTree,
    PersonEmbedding, CircuitEmbedding, PersonCommitment, PersonNullifier,
    QuantizationConfig,
};

fn fr_to_hex(fr: &Fr) -> String {
    format!("0x{}", hex::encode(fr.to_be_bytes()))
}

fn main() {
    let args: Vec<String> = std::env::args().collect();

    let scope = args.get(1)
        .map(|s| s.as_str())
        .unwrap_or("dao-vote-2024");

    let output_path = args.get(2)
        .map(|s| PathBuf::from(s))
        .unwrap_or_else(|| PathBuf::from("Prover.toml"));

    println!("Generating person_identity Prover.toml");
    println!("  Scope: {}", scope);
    println!("  Output: {:?}", output_path);

    let embedding_values: Vec<f32> = (0..128)
        .map(|i| (i as f32 / 128.0) - 0.5)
        .collect();
    let embedding = PersonEmbedding::new(embedding_values);
    println!("  Created 128-dim test embedding");

    let config = QuantizationConfig::default();
    let circuit_embedding = CircuitEmbedding::from_embedding(&embedding, &config);
    println!("  Quantized to {} field elements", circuit_embedding.values.len());

    let blinding = Fr::from_u64(0x1234567890abcdef);
    let commitment = PersonCommitment::with_blinding(&circuit_embedding, blinding);
    println!("  Created commitment");

    let mut tree = MerkleTree::new();
    let index = tree.insert(commitment.value).expect("Insert failed");
    println!("  Inserted commitment at index {}", index);

    let proof = tree.prove(index).expect("Proof generation failed");
    assert!(proof.verify(), "Proof must verify!");
    println!("  Generated valid Merkle proof");

    let nullifier = PersonNullifier::derive(&circuit_embedding, scope);
    println!("  Derived nullifier for scope '{}'", scope);

    let mut toml = String::new();

    toml.push_str("# Auto-generated prover inputs for person_identity circuit\n");
    toml.push_str("# Generated by turing-core::gen_person_prover\n");
    toml.push_str("#\n");
    toml.push_str("# All values are mathematically consistent:\n");
    toml.push_str("# - commitment = Poseidon(COMMITMENT_DOMAIN, compress(embedding), blinding)\n");
    toml.push_str("# - nullifier = Poseidon(NULLIFIER_DOMAIN, compress(embedding), scope)\n");
    toml.push_str("# - merkle_root is computed from REAL tree with commitment as leaf\n");
    toml.push_str("# - merkle_proof is VALID path from commitment to root\n\n");

    toml.push_str(&format!("blinding = \"{}\"\n", fr_to_hex(&blinding)));
    toml.push_str(&format!("commitment = \"{}\"\n", fr_to_hex(&commitment.value)));
    toml.push_str(&format!("merkle_root = \"{}\"\n", fr_to_hex(&proof.root)));
    toml.push_str(&format!("scope = \"{}\"\n", fr_to_hex(&nullifier.scope)));
    toml.push_str(&format!("nullifier = \"{}\"\n\n", fr_to_hex(&nullifier.value)));

    toml.push_str("[embedding]\n");
    toml.push_str("values = [\n");
    for (i, val) in circuit_embedding.values.iter().enumerate() {
        if i > 0 {
            toml.push_str(",\n");
        }
        toml.push_str(&format!("    \"{}\"", fr_to_hex(val)));
    }
    toml.push_str("\n]\n\n");

    toml.push_str("[merkle_proof]\n");
    toml.push_str("path = [\n");
    let path_hex = proof.path_to_hex();
    for (i, val) in path_hex.iter().enumerate() {
        if i > 0 {
            toml.push_str(",\n");
        }
        toml.push_str(&format!("    \"{}\"", val));
    }
    toml.push_str("\n]\n");

    let indices = proof.indices_to_array();
    toml.push_str(&format!("indices = {:?}\n", indices));

    fs::write(&output_path, &toml).expect("Failed to write file");

    println!("\nGenerated Prover.toml:");
    println!("  merkle_root = {} (NOT zero!)", fr_to_hex(&proof.root));
    println!("  commitment  = {}", fr_to_hex(&commitment.value));
    println!("  nullifier   = {}", fr_to_hex(&nullifier.value));
    println!("\nThe proof should now verify successfully!");
}
